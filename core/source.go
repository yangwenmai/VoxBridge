// Package core holds the data shapes shared by the pipeline, the providers
// and the user interfaces. Provider-specific behaviour lives behind the
// interfaces here and is described by Capabilities, never by checking ids.
package core

// Lang is a BCP-47 language tag such as "en", "zh" or "pt-BR".
type Lang string

// SourceKind says how a Source can be played. Live sources only allow
// simultaneous interpretation; vod sources also allow a prepared dub.
type SourceKind string

const (
	SourceLive SourceKind = "live"
	SourceVOD  SourceKind = "vod"
)

// Source is what a link resolves to. DurationMs, Video and Transcript are
// only set for vod sources.
type Source struct {
	Kind  SourceKind `json:"kind"`
	URL   string     `json:"url"`
	Title string     `json:"title"`
	// Language is the spoken language when the platform reports it.
	Language Lang       `json:"language,omitempty"`
	Audio    AudioInput `json:"audio"`

	DurationMs int64          `json:"durationMs,omitempty"`
	Video      *VideoInput    `json:"video,omitempty"`
	Transcript *TranscriptRef `json:"transcript,omitempty"`
}

// AudioInput is a stream ffmpeg can open. Resolved media URLs from video
// platforms expire after a few hours, so a Source is resolved again before
// each run rather than stored.
type AudioInput struct {
	URL string `json:"url"`
	// Headers are the HTTP headers the platform expects when fetching URL.
	Headers  map[string]string `json:"headers,omitempty"`
	Protocol string            `json:"protocol,omitempty"`
	Codec    string            `json:"codec,omitempty"`
}

// VideoInput is the picture track of a vod source.
type VideoInput struct {
	URL     string            `json:"url"`
	Headers map[string]string `json:"headers,omitempty"`
	Width   int               `json:"width,omitempty"`
	Height  int               `json:"height,omitempty"`
}

// TranscriptKind separates captions written by people from speech
// recognition output generated by the platform.
type TranscriptKind string

const (
	TranscriptManual TranscriptKind = "manual"
	TranscriptAuto   TranscriptKind = "auto"
)

// TranscriptRef points at platform subtitles in the spoken language.
type TranscriptRef struct {
	Language Lang           `json:"language"`
	Kind     TranscriptKind `json:"kind"`
	Format   string         `json:"format"`
	URL      string         `json:"url"`
}
